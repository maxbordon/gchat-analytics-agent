"""Builds Google Chat payloads (plain text, Cards v2, add-on responses).

Pure functions with no I/O, which keeps them trivial to unit-test.
"""
from __future__ import annotations

import re
import uuid

from .response_parser import AgentAnswer, Table

MAX_TABLE_ROWS = 10
MAX_TABLE_COLUMNS = 5

_HEADER = re.compile(r"^(#{1,6})\s+(.*)$")
_BULLET = re.compile(r"^(\s*)[*\-]\s+(.*)$")
_BOLD = re.compile(r"\*\*(.+?)\*\*")


def markdown_to_chat(text: str, for_card: bool = False) -> str:
    """Convert the agent's Markdown to Chat syntax.

    Plain messages use *bold*; card text paragraphs use a small HTML subset.
    """
    out = []
    for line in text.split("\n"):
        header = _HEADER.match(line)
        if header:
            title = header.group(2).strip()
            line = f"<b>{title}</b>" if for_card else f"*{title}*"

        bullet = _BULLET.match(line)
        if bullet:
            line = f"{bullet.group(1)}• {bullet.group(2)}"

        line = _BOLD.sub(r"<b>\1</b>" if for_card else r"*\1*", line)
        out.append(line)

    joined = "\n".join(out)
    return joined.replace("\n", "<br>") if for_card else joined


def addon_message(text: str) -> dict:
    """Synchronous reply format when the Chat app is a Workspace add-on."""
    return {
        "hostAppDataAction": {
            "chatDataAction": {"createMessageAction": {"message": {"text": text}}}
        }
    }


def table_widgets(table: Table) -> list[dict]:
    columns = table.columns[:MAX_TABLE_COLUMNS]
    rows = table.rows[:MAX_TABLE_ROWS]
    if not columns or not rows:
        return []

    widgets = [{"textParagraph": {"text": " · ".join(f"<b>{c}</b>" for c in columns)}}]
    for row in rows:
        cells = [row[i] if i < len(row) else "" for i in range(len(columns))]
        widgets.append({"textParagraph": {"text": " · ".join(cells)}})

    if len(table.rows) > MAX_TABLE_ROWS:
        widgets.append({
            "textParagraph": {
                "text": f"<i>Showing {MAX_TABLE_ROWS} of {len(table.rows)} rows. "
                        "Narrow the question to see fewer.</i>"
            }
        })
    return widgets


def answer_card(answer: AgentAnswer, bot_name: str, chart_url: str | None = None) -> dict:
    sections = []
    if answer.text:
        sections.append({"widgets": [{"textParagraph": {"text": markdown_to_chat(answer.text, for_card=True)}}]})

    if answer.table:
        widgets = table_widgets(answer.table)
        if widgets:
            sections.append({
                "header": "Data",
                "collapsible": True,
                "uncollapsibleWidgetsCount": 1,
                "widgets": widgets,
            })

    if chart_url:
        sections.append({
            "widgets": [{
                "image": {
                    "imageUrl": chart_url,
                    "altText": f"Chart generated by {bot_name}",
                    # Without onClick, Chat doesn't let users open/zoom the image.
                    "onClick": {"openLink": {"url": chart_url}},
                }
            }]
        })

    return {
        "cardsV2": [{
            "cardId": f"answer-{uuid.uuid4().hex[:12]}",
            "card": {"header": {"title": bot_name}, "sections": sections},
        }]
    }
